"""Run the eval dataset through the real pipeline and produce a metrics report.

Requires a populated Pinecone index (run `python -m src.ingest` first) and
valid PINECONE_API_KEY / GROQ_API_KEY in .env -- this hits live APIs, it does
not mock anything, so the numbers it prints are real for whatever the index
currently contains.

Usage:
    python eval/run_eval.py
Outputs:
    eval/eval_output.json   (raw per-question results)
    eval/eval_results.md    (human-readable table, overwritten each run)
"""
import json
import os
import sys
import time

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

from src.vectorstore import get_pinecone_client, VectorStore
from src.embeddings import Embedder
from src.llm import LLMClient
from src.graph import build_graph, run_query

HERE = os.path.dirname(__file__)


def load_dataset():
    with open(os.path.join(HERE, "eval_dataset.json"), encoding="utf-8") as f:
        return json.load(f)


def context_sufficiency(sources, threshold=0.6):
    """Fraction of retrieved chunks that clear a basic 'plausibly relevant' bar."""
    if not sources:
        return 0.0
    good = [s for s in sources if s["score"] >= threshold]
    return round(len(good) / len(sources), 2)


def main():
    dataset = load_dataset()

    pc = get_pinecone_client()
    vectorstore = VectorStore(pc)
    vectorstore.ensure_index()
    embedder = Embedder(pc)
    llm_client = LLMClient()
    app = build_graph(embedder, vectorstore, llm_client)

    results = []
    for item in dataset:
        start = time.time()
        r = run_query(app, item["question"])
        latency = round(time.time() - start, 2)

        top_score = r["sources"][0]["score"] if r["sources"] else 0.0
        expected_fallback = item["category"] == "out_of_knowledge_base"

        results.append({
            "id": item["id"],
            "category": item["category"],
            "question": item["question"],
            "answer": r["answer"],
            "used_fallback": r["used_fallback"],
            "expected_fallback_behavior": expected_fallback,
            "fallback_behavior_correct": r["used_fallback"] == expected_fallback
            if item["category"] == "out_of_knowledge_base"
            else not r["used_fallback"],
            "top_retrieval_score": round(top_score, 4),
            "context_sufficiency": context_sufficiency(r["sources"]),
            "confidence": r["confidence"],
            "groundedness": r["groundedness"],
            "num_sources": len(r["sources"]),
            "latency_sec": latency,
        })
        print(f"[{item['id']}] fallback={r['used_fallback']} "
              f"confidence={r['confidence']} groundedness={r['groundedness']}")

    with open(os.path.join(HERE, "eval_output.json"), "w", encoding="utf-8") as f:
        json.dump(results, f, indent=2)

    write_markdown_report(results)
    print("\nWrote eval/eval_output.json and eval/eval_results.md")


def _fmt(value):
    return "n/a" if value is None else value


def write_markdown_report(results):
    total = len(results)
    fb_correct_count = sum(1 for r in results if r["fallback_behavior_correct"])
    oob_results = [r for r in results if r["category"] == "out_of_knowledge_base"]
    answerable_results = [r for r in results if r["category"] != "out_of_knowledge_base"]
    measured_groundedness = [r["groundedness"] for r in results if r["groundedness"] is not None]

    avg_confidence = round(sum(r["confidence"] for r in results) / total, 3) if total else 0
    avg_groundedness = (
        round(sum(measured_groundedness) / len(measured_groundedness), 3)
        if measured_groundedness else None
    )
    avg_retrieval = round(sum(r["top_retrieval_score"] for r in results) / total, 3) if total else 0

    lines = [
        "# Evaluation Results",
        "",
        "Auto-generated by `eval/run_eval.py` against the live pipeline "
        f"on {len(results)} questions from `eval_dataset.json`.",
        "",
        "## Summary",
        "",
        f"- Fallback behavior correct: **{fb_correct_count}/{total}** "
        f"({len(oob_results)} out-of-knowledge-base, {len(answerable_results)} answerable)",
        f"- Average top retrieval score: **{avg_retrieval}**",
        f"- Average confidence: **{avg_confidence}**",
        f"- Average groundedness (measured cases only): "
        f"**{avg_groundedness if avg_groundedness is not None else 'n/a -- no answer was graded this run'}** "
        f"({len(measured_groundedness)}/{total} answers had a measured groundedness score; "
        "the rest were model refusals or a failed grading call, both of which skip "
        "grading by design -- see README)",
        f"- `correctness` column: **pending manual review** -- intentionally not automated, "
        "since judging it requires comparing each answer against the actual ebook text "
        "(no gold-answer dataset exists for that). Fill it in after reading the "
        "generated answers below.",
        "",
        "## Per-question results",
        "",
        "| id | category | fallback used | correct fallback behavior | top retrieval score | context sufficiency | confidence | groundedness | correctness |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in results:
        fb_correct_str = "yes" if r["fallback_behavior_correct"] else "NO"
        lines.append(
            f"| {r['id']} | {r['category']} | {r['used_fallback']} | {fb_correct_str} | "
            f"{r['top_retrieval_score']} | {r['context_sufficiency']} | {r['confidence']} | "
            f"{_fmt(r['groundedness'])} | Pending |"
        )

    lines.append("")
    lines.append("## Answers")
    for r in results:
        lines.append(f"\n### {r['id']} ({r['category']}) -- {r['question']}\n")
        lines.append(r["answer"])

    with open(os.path.join(HERE, "eval_results.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
